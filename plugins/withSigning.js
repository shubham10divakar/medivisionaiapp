/**
 * Expo config plugin: sign debug + release builds with keystores kept OUTSIDE the
 * app folder, so they survive `expo prebuild --clean` and never land in git.
 *
 * Keystore folder (first match wins):
 *   1. Gradle property  MEDIVISION_KEYSTORE_DIR  (e.g. in ~/.gradle/gradle.properties)
 *   2. Env variable     MEDIVISION_KEYSTORE_DIR
 *   3. <app>/../keystores
 *
 * Expected contents: debug.keystore, medivision.keystore, keystore.properties.
 * If the folder is missing, builds fall back to the Expo template debug key.
 * See LOCAL_BUILD.md.
 */
const { withAppBuildGradle } = require('expo/config-plugins');

const MARKER = '// @medivision-signing';

const SIGNING_BLOCK = `${MARKER} (generated by plugins/withSigning.js)
    def mvKeystoreDir = file(findProperty('MEDIVISION_KEYSTORE_DIR') ?: System.getenv('MEDIVISION_KEYSTORE_DIR') ?: "\${rootDir}/../../keystores")
    def mvSigning = new Properties()
    def mvSigningFile = new File(mvKeystoreDir, 'keystore.properties')
    if (mvSigningFile.exists()) {
        mvSigningFile.withInputStream { mvSigning.load(it) }
    }
    def mvDebugKeystore = new File(mvKeystoreDir, 'debug.keystore')
    def mvHasRelease = mvSigning.getProperty('releaseStoreFile') != null
    signingConfigs {
        debug {
            storeFile mvDebugKeystore.exists() ? mvDebugKeystore : file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        release {
            if (mvHasRelease) {
                storeFile new File(mvKeystoreDir, mvSigning.getProperty('releaseStoreFile'))
                storePassword mvSigning.getProperty('releaseStorePassword')
                keyAlias mvSigning.getProperty('releaseKeyAlias')
                keyPassword mvSigning.getProperty('releaseKeyPassword')
            }
        }
    }`;

function applySigning(gradle) {
  if (gradle.includes(MARKER)) return gradle;

  // 1. release buildType: use the release key when it is configured.
  const releaseRe = /(release \{[\s\S]*?)signingConfig signingConfigs\.debug/;
  if (!releaseRe.test(gradle)) {
    throw new Error('withSigning: release buildType not found in app/build.gradle');
  }
  let out = gradle.replace(
    releaseRe,
    '$1signingConfig mvHasRelease ? signingConfigs.release : signingConfigs.debug'
  );

  // 2. replace the template signingConfigs block.
  const blockRe = /signingConfigs \{\s*debug \{[^}]*\}\s*\}/;
  if (!blockRe.test(out)) {
    throw new Error('withSigning: signingConfigs block not found in app/build.gradle');
  }
  return out.replace(blockRe, () => SIGNING_BLOCK);
}

const withSigning = (config) =>
  withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error('withSigning: only Groovy build.gradle is supported');
    }
    cfg.modResults.contents = applySigning(cfg.modResults.contents);
    return cfg;
  });

module.exports = withSigning;
module.exports.applySigning = applySigning;
